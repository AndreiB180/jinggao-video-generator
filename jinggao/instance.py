"""An OS-released lock prevents two launchers from recovering the same job queue."""
from __future__ import annotations

import os

from . import paths


def acquire(name="instance.lock"):
    paths.prepare()
    handle = (paths.DATA / name).open("a+b")
    handle.seek(0, 2)
    if handle.tell() == 0:
        handle.write(b"0")
        handle.flush()
    handle.seek(0)
    try:
        if os.name == "nt":
            import msvcrt
            msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
        else:
            import fcntl
            fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        handle.close()
        return None
    return handle
